    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String pid=patientId.getText();
        int patientid=Integer.parseInt(pid);
        String pname=patientAge.getText();
        String page=patientAge.getText();
        int patientAge=Integer.parseInt(page);
        String dname=dName.getText();
        try{
            //Load Driver
            Class.forName("com.mysql.cj.jdbc.Driver");
            //Create Connection
            Connection con=DriverManager.getConnection("jdbc:mysql://localhost:3306/Hospital","root","toshiba@123");
            String query="INSERT INTO patient VALUES(?,?,?,?)";
            PreparedStatement pstmt=con.prepareStatement(query);
            pstmt.setInt(1,patientid);
            pstmt.setString(2,pname);
            pstmt.setInt(3,patientAge);
            pstmt.setString(4,dname);
            //execute query
            pstmt.executeUpdate();
            con.close();
            JOptionPane.showMessageDialog(this, "Data Inserted......");
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

