    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
            String doctorName=dname.getText();
         try{
             DefaultTableModel model=(DefaultTableModel)Table.getModel();
            //Load Driver
            Class.forName("com.mysql.cj.jdbc.Driver");
            //Create Connection
            Connection con=DriverManager.getConnection("jdbc:mysql://localhost:3306/Hospital","root","toshiba@123");
            //String query="SELECT * FROM patient WHERE id == ?";
            PreparedStatement pstmt=con.prepareStatement("SELECT * FROM doctor WHERE id=?");
            pstmt.setString(1,doctorName);
            ResultSet rs= pstmt.executeQuery();
            while(rs.next()){
                         int did=rs.getInt("id");
                         String doctorId=Integer.toString(did);
                         String dname=rs.getString("name");
                         String dDepartment=rs.getString("department");                        
                         //String dname=rs.getString("doctor_name");
                         String row[]={doctorId,dname,dDepartment};
                         model.addRow(row);
            }
            con.close();
         }catch(Exception e){
             JOptionPane.showMessageDialog(this, e);
         }
    }//GEN-LAST:event_jButton1ActionPerformed

